#!/usr/bin/env python3
"""Embed the pinned oracle JSON for identical JVM and Native common tests."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "testdata" / "py-fsrs-6.3.1-vectors.json"
TARGET = ROOT / "src" / "commonTest" / "kotlin" / "tech" / "kelma" / "fsrs" / "OracleFixtureData.kt"
EXPECTED_SHA256 = "27c0777605a7ce95e1eaf38200bbe2e0b6daf41d8227486a6b4a84d427db8c1c"
CHUNK_SIZE = 12_000


def main() -> None:
    payload = SOURCE.read_bytes()
    digest = hashlib.sha256(payload).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"fixture SHA-256 {digest}, expected {EXPECTED_SHA256}")
    text = payload.decode("utf-8")
    chunks = [text[index : index + CHUNK_SIZE] for index in range(0, len(text), CHUNK_SIZE)]
    lines = [
        "// Generated by tools/embed_fixture.py. Do not edit by hand.",
        "package tech.kelma.fsrs",
        "",
        f'internal const val OracleFixtureSha256 = "{EXPECTED_SHA256}"',
        "internal val OracleFixtureJson: String = listOf(",
    ]
    lines.extend(f"    {json.dumps(chunk)}," for chunk in chunks)
    lines.extend((
        ").joinToString(separator = \"\")",
        "",
    ))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"embedded {len(payload)} bytes in {len(chunks)} chunks")


if __name__ == "__main__":
    main()
